import { useEffect, useRef, useState } from 'react'
import { getHeroStageSrc } from '../utils/heroManifest'
import './HeroStage.css'

// The hero-coloured platform background shown behind every hero sprite/
// emote - the shared wrapper every screen that plays a hero animation
// (HeroDetailModal's HeroEmoteStage, EmoteShowcase's pedestal, the Me tab's
// hero display, AthleteTerritoryProfilePanel's profile popup, HeroGallery's
// roster carousel) renders its sprite inside, so they all get the same
// stage. `src` comes from heroManifest.js's getHeroStageSrc
// (src/assets/heroes/<hero>/stage.webp, generated by scripts/make-stages.mjs
// from stage_base.webp).
//
// `children` is either a plain node (rendered as-is - only HeroDetailModal
// does this, see its own call site for why) or a function
// `(heroHeight) => node`: this component measures its OWN rendered box via
// ResizeObserver and hands back 80% of that height, not a hardcoded pixel
// constant - a hero sized off the box it's actually standing in instead of
// its own sprite's native size is what keeps it from ever being taller
// than the stage (the bug this component was rewritten to fix - see git
// history). The 20% left over is headroom above the head, enough for an
// emote pose taller than idle (jump/arms-up), not just idle itself.
//
// No background layer here, and overflow: visible (not hidden) - stage.webp
// is meant to show whatever panel colour already sits behind HeroStage,
// and a hero that's briefly mid-measurement (before the very first
// ResizeObserver callback) must not get clipped while it settles.
export default function HeroStage({
  hero,
  children,
  className = '',
  fullBleed = false,
}) {
  const src = getHeroStageSrc(hero)
  const stageRef = useRef(null)
  const [stageHeight, setStageHeight] = useState(0)

  const measuring = typeof children === 'function'
  useEffect(() => {
    const el = stageRef.current
    // Keyed on `measuring`, not `children` itself - an inline arrow
    // function prop (every call site using this form) is a new reference
    // every render, which would tear down and recreate the observer on
    // every single re-render for no reason.
    if (!el || !measuring) return undefined
    const ro = new ResizeObserver(([entry]) =>
      setStageHeight(entry.contentRect.height)
    )
    ro.observe(el)
    return () => ro.disconnect()
  }, [measuring])

  const heroHeight = stageHeight ? Math.round(stageHeight * 0.8) : 0

  return (
    <div ref={stageRef} className={`hero-stage ${className}`}>
      <img
        className="hero-stage-bg"
        src={src}
        alt=""
        aria-hidden="true"
        loading="lazy"
        width={1000}
        height={778}
      />
      <span className="hero-stage-glow" aria-hidden="true" />
      <div className={`hero-stage-figure ${fullBleed ? 'is-full' : ''}`}>
        {typeof children === 'function' ? children(heroHeight) : children}
      </div>
    </div>
  )
}
